/**
 * 点位的「室内/户外」推断 —— 生成时的雨天适配要用：
 * 预报当天有雨，就把室内的项排在前面（见 itinerary.ts 的天气适配层）。
 *
 * 口径：名字命中「封闭场馆/商业体」类关键词判室内；
 * 没有命中「公园·山·湖·岛…」这类户外词、也不命中室内词的点位
 * 返回 false（保守当户外，宁多穿雨衣不困室内）。
 *
 * 内置库和在线库（cityPoi.toSeed）共用同一把尺子，避免两边标注漂移。
 */

const INDOOR_WORDS = [
  '博物馆',
  '纪念馆',
  '陈列馆',
  '展览',
  '美术馆',
  '科技馆',
  '海洋馆',
  '水族',
  '天文馆',
  '自然馆',
  '规划馆',
  '艺术中心',
  '剧院',
  '音乐厅',
  '图书馆',
  '温室',
  '室内',
  '商城',
  '大厦',
  '大楼',
  '百货',
  '老街', // 商业街虽无顶，但雨天步行滑→多数用户仍视为不宜；归室内侧提示更稳
  '步行街',
  '庙会',
  '温泉', // 室内汤池为主
  '冰雪',
  '滑雪'
]

const OUTDOOR_WORDS = [
  '公园',
  '山',
  '峰',
  '岭',
  '湖',
  '海',
  '滩',
  '岛',
  '屿',
  '洲',
  '湾',
  '江',
  '河',
  '溪',
  '谷',
  '林',
  '草原',
  '湿地',
  '沙漠',
  '田野',
  '梯田',
  '栈道',
  '天池',
  '瀑',
  '溶洞'
]

export function isIndoorPoi(name: string, area = ''): boolean {
  const s = `${name} ${area}`
  // 场馆词（博物馆/海洋馆…）更具体 —— 先判；「海底世界海洋馆」不能被外部的「海」抢走
  for (const w of INDOOR_WORDS) if (s.includes(w)) return true
  for (const w of OUTDOOR_WORDS) if (s.includes(w)) return false
  return false
}
